export const normalizeTemplateDisciplineIds = (
  disciplineIds: unknown,
  disciplines: ActionPlanDiscipline[],
): string[] => {
  if (!Array.isArray(disciplineIds)) return [];

  const validDisciplineIds = new Set(disciplines.map((discipline) => discipline.id));
  return Array.from(
    new Set(
      disciplineIds.filter(
        (disciplineId): disciplineId is string =>
          typeof disciplineId === "string" && validDisciplineIds.has(disciplineId),
      ),
    ),
  );
};

export const templateMatchesDiscipline = (
  template: Pick<ActionPlanTemplate, "disciplineIds">,
  disciplineId?: string,
): boolean => {
  if (template.disciplineIds.length === 0) return true;
  if (!disciplineId) return false;
  return template.disciplineIds.includes(disciplineId);
};

export const getTemplateDisciplineLabels = (
  disciplineIds: string[],
  disciplines: ActionPlanDiscipline[],
): string[] => {
  const labelsById = new Map(disciplines.map((discipline) => [discipline.id, discipline.title]));
  return disciplineIds.map((disciplineId) => labelsById.get(disciplineId) ?? disciplineId);
};

// Handlungen tragen die Kategorie ihrer Vorlage; fehlt sie (aeltere Handlungen),
// wird sie ueber die referenzierte Vorlage nachgeschlagen. Aeltere Handlungen kennen
// nur den frueheren Vorlagennamen (= Titel), darum dieser als letzter Rueckfall.
export const getActionCategoryId = (
  action: Pick<ActionNode, "categoryId" | "templateId" | "templateName">,
  templates: Pick<ActionPlanTemplate, "id" | "fields" | "categoryId">[],
): string | undefined => {
  // "" heisst: bewusst «Ohne Kategorie» zugeteilt, kein Rueckfall auf die Vorlage.
  if (action.categoryId !== undefined) return action.categoryId || undefined;
  const template = action.templateId
    ? templates.find((entry) => entry.id === action.templateId)
    : action.templateName
      ? templates.find((entry) => entry.fields.titel === action.templateName)
      : undefined;
  return template?.categoryId;
};

// Waehlbar sind die Kategorien aller zugeteilten Disziplinen (Vereinigung).
export const getAvailableCategories = (
  disciplineIds: string[],
  disciplines: ActionPlanDiscipline[],
  categories: ActionPlanCategory[],
): ActionPlanCategory[] => {
  const categoryIds = new Set(
    disciplines
      .filter((discipline) => disciplineIds.includes(discipline.id))
      .flatMap((discipline) => discipline.categoryIds),
  );
  return sortActionPlanCategories(categories.filter((category) => categoryIds.has(category.id)));
};

export const resolveTemplateCategoryId = (
  value: string,
  categories: ActionPlanCategory[],
): { categoryId?: string; invalid: boolean } => {
  const normalized = value.trim().toLocaleLowerCase("de");
  if (!normalized) return { invalid: false };
  const category = categories.find(
    (entry) =>
      entry.code.toLocaleLowerCase("de") === normalized ||
      entry.name.toLocaleLowerCase("de") === normalized ||
      `${entry.code} ${entry.name}`.toLocaleLowerCase("de") === normalized,
  );
  return category ? { categoryId: category.id, invalid: false } : { invalid: true };
};

export const resolveTemplateDisciplineIds = (
  value: string,
  disciplines: ActionPlanDiscipline[],
): { disciplineIds: string[]; invalidEntries: string[] } => {
  const entries = value
    .split(",")
    .map((entry) => entry.trim())
    .filter(Boolean);
  const disciplineById = new Map(disciplines.map((discipline) => [discipline.id.toLocaleLowerCase("de"), discipline]));
  const disciplineByTitle = new Map(disciplines.map((discipline) => [discipline.title.toLocaleLowerCase("de"), discipline]));
  const disciplineIds: string[] = [];
  const invalidEntries: string[] = [];

  entries.forEach((entry) => {
    const normalized = entry.toLocaleLowerCase("de");
    const discipline = disciplineById.get(normalized) ?? disciplineByTitle.get(normalized);
    if (!discipline) {
      invalidEntries.push(entry);
      return;
    }
    if (!disciplineIds.includes(discipline.id)) disciplineIds.push(discipline.id);
  });

  return { disciplineIds, invalidEntries };
};

